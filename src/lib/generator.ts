function buildDescription(
  workType: WorkType,
  productionType: ProductionType,
  industryOption: string,
  memo: string,
): string {
  const opener = OPENERS[productionType];
  const industryCtx = getIndustryContext(workType, industryOption);
  const endPhrase = WORK_TYPE_END[workType][productionType];
  const body = DESC_BODY[workType];

  const para1 = `${opener}、${industryCtx}${endPhrase}`;
  const para2 = body.p2;
  const para3 = body.p3;

  const base = `${para1}\n\n${para2}\n\n${para3}`;
  return memo.trim() ? `${base}\n\n${memo.trim()}` : base;
}

