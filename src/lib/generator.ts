function buildKeywords(
  workType: WorkType,
  industryOption: string,
  categoryOption: string,
): string {
  const base = [...BASE_KEYWORDS[workType]];
  const industry = INDUSTRY_KEYWORDS[industryOption] ?? [];

  const combined = [...base, ...industry];

  // Add categoryOption as a keyword if not already present
  if (categoryOption && !combined.includes(categoryOption)) {
    combined.splice(2, 0, categoryOption);
  }

  return [...new Set(combined)].slice(0, 10).join(', ');
}

